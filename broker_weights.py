def get_broker_weight(broker_name: str) -> float:
    """
    获取券商权重，未定义的券商返回默认权重0.5
    """
    # 处理可能的名称变体（如"中信证券" vs "中信证券股份有限公司"）
    for key, weight in BROKER_WEIGHTS.items():
        if key in broker_name or broker_name in key:
            return weight
    
    # 尝试模糊匹配
    if '证券' in broker_name:
        return 0.6  # 默认给国内券商0.6
    elif '国际' in broker_name or '投行' in broker_name:
        return 0.5  # 外资默认0.5
    
    return 0.5  # 默认权重
